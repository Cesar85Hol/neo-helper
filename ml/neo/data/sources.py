"""Catalogue of the dataset sources: where each file comes from, its size,
checksum and licence.

File lists, sizes and MD5 checksums are pinned here on purpose: a download is
accepted only if it matches, so everyone works on exactly the same files.
They were read from the repository APIs on the date given in ``checked``.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class RemoteFile:
    """One file to download."""

    name: str  # file name on disk
    url: str
    size: int  # bytes
    md5: str
    group: str = "core"  # files are downloaded by group; "core" is the default


@dataclass(frozen=True)
class Source:
    """One dataset as published by its authors."""

    key: str  # short name used on the command line and in the registry
    title: str
    license: str
    license_url: str
    doi: str
    landing_page: str
    version: str
    checked: str  # date the catalogue entry was read from the repository
    files: tuple[RemoteFile, ...] = field(default_factory=tuple)

    def groups(self) -> list[str]:
        return sorted({f.group for f in self.files}, key=lambda g: (g != "core", g))

    def select(self, groups: list[str] | None = None) -> list[RemoteFile]:
        wanted = set(groups or ["core"])
        unknown = wanted - set(self.groups())
        if unknown:
            raise ValueError(
                f"Unknown group(s) {sorted(unknown)} for '{self.key}'. Available: {self.groups()}"
            )
        return [f for f in self.files if f.group in wanted]


