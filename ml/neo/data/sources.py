SOURCES: dict[str, Source] = {s.key: s for s in (HAM10000, CHANDA2024)}


def get_source(key: str) -> Source:
    if key not in SOURCES:
        raise ValueError(f"Unknown dataset '{key}'. Available: {sorted(SOURCES)}")
    return SOURCES[key]
